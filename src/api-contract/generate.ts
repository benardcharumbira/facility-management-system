/** Seeds the mock the way development does, so the examples are the data a reviewer sees. */
export function seedMock(now: DateTime = EXAMPLE_NOW) {
  seedBookings(now);
  seedApprovals(now);
  seedFacilityAdmin(now);
  seedUnroutedRequests(now);
  seedSpanRequests(now);
  seedAudit(now);
}

const HEADER =
  '# GENERATED by `npm run api:generate` from src/shared/api/schemas. Do not edit by hand.\n';

/** Every operation, by the slice that defined it, as a checklist. */
function inventory(exampleCounts: Map<string, number>): string {
  const bySlice = new Map<number, typeof OPERATIONS>();
  for (const operation of OPERATIONS) {
    bySlice.set(operation.slice, [...(bySlice.get(operation.slice) ?? []), operation]);
  }
  const lines = [
    '<!-- GENERATED by `npm run api:generate`. Do not edit by hand. -->',
    '',
    '# Inventory',
    '',
    `Every operation the frontend calls, by the slice that defined it: ${OPERATIONS.length} in all. A tick means the operation is in \`openapi.yaml\` with a request and response schema and at least one example captured from the mock. Where a handler and a slice prompt disagreed, see [DISCREPANCIES.md](DISCREPANCIES.md).`,
    '',
  ];
  for (const slice of [...bySlice.keys()].sort((a, b) => a - b)) {
    lines.push(`## Slice ${slice}`, '');
    for (const op of bySlice.get(slice) ?? []) {
      const examples = exampleCounts.get(op.id) ?? 0;
      const tick = examples > 0 ? 'x' : ' ';
      lines.push(
        `- [${tick}] \`${op.method.toUpperCase()} /api${op.path}\` — ${op.summary} _(${accessSentence(op.access).replace(/\.$/, '')}; ${examples} example${examples === 1 ? '' : 's'})_`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}

export interface Artifacts {
  openapi: string;
  inventory: string;
}

/** Captures the examples through `call` and builds everything that is published. */
export async function generateArtifacts(call: Caller): Promise<Artifacts> {
  const captured = await captureExamples(call);
  const counts = new Map<string, number>();
  for (const example of captured) {
    counts.set(example.operationId, (counts.get(example.operationId) ?? 0) + 1);
  }
  const document = buildOpenApi(captured);
  return {
    openapi:
      HEADER +
      stringify(document, { lineWidth: 0, aliasDuplicateObjects: false, schema: 'yaml-1.1' }),
    inventory: inventory(counts),
  };
}
